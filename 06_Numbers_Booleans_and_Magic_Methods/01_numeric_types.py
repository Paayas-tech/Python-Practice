# 1. Integers (int)
count = 100
large_num = 1_000_000  # Underscores for readability
print(count, large_num)

# 2. Floating-point numbers (float)
price = 19.99
rate = 2.5e3  # Scientific notation (2.5 * 10^3 = 2500.0)
print(price, rate)
print(round(5.6789, 2))  # 5.68

# 3. Complex numbers (complex)
comp = 3 + 5j
print(comp.real, comp.imag)  # Real: 3.0, Imaginary: 5.0