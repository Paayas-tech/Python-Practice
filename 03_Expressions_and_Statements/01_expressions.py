# Expressions always evaluate to a single value

# Arithmetic expressions
5 + 3
total = 10 * 2  # '10 * 2' is an expression evaluated to 20

# Comparison expressions (evaluate to True / False)
is_greater = 15 > 8  # Evaluates to True

# Function calls are expressions (they evaluate to their return value)
length = len("Data Analytics")

# String operations as expressions
full_text = "Python " + "Practice"

print(total, is_greater, length, full_text)